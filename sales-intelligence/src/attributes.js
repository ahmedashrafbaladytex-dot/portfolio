function match(text, dict) {
  // الأطول أولاً عشان "قطن مصري" تكسب "قطن" و"أوف وايت" تكسب "أبيض"
  let best = null, bestLen = 0;
  for (const [label, ...words] of dict) {
    for (const w of words) {
      const nw = norm(w);
      const re = new RegExp(`(^|\\s)(و|ب|ال|بال|وال)?${nw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
      if (re.test(text) && nw.length > bestLen) { best = label; bestLen = nw.length; }
    }
  }
  return best;
}

function inferAttributes(name) {
  const t = norm(name);
  const dim = t.match(/(\d{2,3})\s*[x×*]\s*(\d{2,3})/);
  return {
    category: match(t, CATEGORIES) || '',
    fabric: match(t, FABRICS) || '',
    color: match(t, COLORS) || '',
    pattern: match(t, PATTERNS) || '',
    size: match(t, SIZES) || (dim ? `${dim[1]}×${dim[2]}` : ''),
  };
}

